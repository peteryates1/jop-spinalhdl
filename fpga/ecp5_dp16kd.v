// ECP5 DP16KD block RAM, with the clock-to-out yosys leaves out (status item
// 175). fpga/ecp5.mk reads this over yosys's own model, after synth_ecp5's
// `begin` step, for every JOP board flow on the ECP5.
//
// WHY. yosys's DP16KD is a blackbox with no timing, so ABC9 takes its outputs
// as arriving with the clock, like a flop's. nextpnr (speed 6) has them 5.8 ns
// after it. ABC9 maps for delay and then recovers area on every path up to one
// global ceiling, the slowest path it can see -- so a path that starts at a
// RAM is deepened until it matches whatever unrelated flop-to-flop logic is
// slowest. On the i5 that path is JOP's critical one (bytecode RAM -> jump
// table -> microcode ROM address), and adding Ethernet moved the build by
// 9 MHz without touching the fetch RTL: 13 LUT levels without, 10 with.
//
// THE VALUE is the RAM's lateness in ABC9's units, not nextpnr's. A flop's
// clock-to-out is 0.5 ns in nextpnr and 0 in yosys's model, so the RAM is
// 5.3 ns later than a flop. ABC9 prices a LUT level at 141-379 ps plus the
// 300 ps wire delay synth_ecp5 gives it (-W 300); routed, a level costs about
// 1.3 ns. 5.3 ns is therefore about four levels, about 2.5 ns to ABC9.
// Measured on all four i5 presets over nextpnr seeds 1-8 (item 175): of 2000,
// 2500 and 3000 ps, only 2500 raised every preset's mean AND its worst seed,
// and the means differ by less than the seed spread. The physical 5300 ps
// over-weights the RAM, and ABC9 deepens the flop paths instead.
//
// yosys's ECP5 RAM mapping only ever instantiates DP16KD with REGMODE "NOREG"
// (brams_map.v), which is what this delay is for; an output-registered RAM
// would be far earlier.
//
// Everything from `(* blackbox *)` down to `specify` is yosys 0.52's own
// declaration (techlibs/ecp5/cells_sim.v, ISC licence), byte for byte, so that
// every parameter synth_ecp5's mapping sets still exists:
// .github/scripts/check-ecp5-bram-timing.sh holds it to the installed yosys.
