package jop.generate

import jop.config._

/**
 * Vivado .xdc Constraint File Generator
 *
 * Generates set_property PACKAGE_PIN / IOSTANDARD constraints from JopConfig.
 * Uses PinResolver for shared pin resolution.
 *
 * Xilinx-specific features:
 *   - create_clock for board oscillator
 *   - resetn for default clock domain (active-low)
 *   - IOSTANDARD on every pin
 *   - SDR SDRAM IOB packing (inlined)
 *   - CFGBVS / CONFIG_VOLTAGE / BITSTREAM.GENERAL.COMPRESS
 *
 * DDR3 pins are managed by MIG IP and not included here.
 */
object XdcGenerator {

  /** Generate complete XDC constraint file */
  def generate(config: BoardDesign): String = {
    val assembly = config.assembly
        val sb = new StringBuilder

    sb.append("# Generated by JOP XdcGenerator\n")
    sb.append(s"# Assembly: ${assembly.name}\n")
    sb.append(s"# System: ${config.designName}\n\n")

    // Clock
    PinResolver.clockFpgaPin(assembly).foreach { pin =>
      val freqHz = assembly.boardClockFreq.toBigDecimal
      val periodNs = (BigDecimal("1000000000") / freqHz)
        .setScale(3, BigDecimal.RoundingMode.HALF_UP)
      sb.append("# System clock\n")
      sb.append(pinConstraint(pin, "clk"))
      sb.append(s"create_clock -period $periodNs -name sys_clk [get_ports {clk}]\n\n")
    }

    // Reset, from the same config predicate JopTop and QsfGenerator use, so
    // the port NAME is not restated here (Xilinx "resetn" vs Altera "reset_n").
    config.resetInput.foreach { r =>
      sb.append(s"# Reset (active ${if (r.activeLow) "low" else "high"})\n")
      sb.append(pinConstraint(r.pin, r.port))
      sb.append("\n")
    }

    // Separate device pins into UART and others
    val allDriverPins = PinResolver.devicePins(assembly, config.devices)
    val uartPins = allDriverPins.filter(_.verilogPort.startsWith("ser_"))
    val otherDriverPins = allDriverPins.filterNot(_.verilogPort.startsWith("ser_"))

    // UART
    if (uartPins.nonEmpty) {
      sb.append("# UART\n")
      uartPins.foreach(p => sb.append(pinConstraint(p.fpgaPin, p.verilogPort)))
      sb.append("\n")
    }

    // LEDs
    val leds = PinResolver.ledPins(assembly).take(config.ledCount)
    if (leds.nonEmpty) {
      sb.append("# LEDs\n")
      leds.foreach(p => sb.append(pinConstraint(p.fpgaPin, p.verilogPort)))
      sb.append("\n")
    }

    // SDR SDRAM — only when the SYSTEM uses it, not merely when the board has
    // the chip. The Wukong carries both an SDR part and DDR3, so filtering on
    // the assembly alone emitted 40-odd sdram_* constraints into a DDR3 build
    // for ports that design does not have. Vivado only warns about those, which
    // is worse than failing: the file looks right and the warning scrolls past.
    val usesSdr = config.usesSdr
    val sdramClk = if (usesSdr) PinResolver.sdramClockFpgaPin(assembly) else None
    val sdramPins = if (usesSdr) PinResolver.sdramPins(assembly) else Seq.empty
    if (sdramPins.nonEmpty || sdramClk.isDefined) {
      sb.append("# SDR SDRAM\n")
      sdramClk.foreach(pin => sb.append(pinConstraint(pin, "sdram_clk")))

      // Group SDRAM pins by category for readability
      val ctrl = sdramPins.filter(p => Seq("CKE", "CSn", "RASn", "CASn", "WEn")
        .exists(s => p.verilogPort == s"sdram_$s"))
      val ba = sdramPins.filter(_.verilogPort.startsWith("sdram_BA"))
        .sortBy(_.verilogPort)
      val dqm = sdramPins.filter(_.verilogPort.startsWith("sdram_DQM"))
        .sortBy(_.verilogPort)
      val addr = sdramPins.filter(_.verilogPort.startsWith("sdram_ADDR"))
        .sortBy(p => extractIndex(p.verilogPort))
      val dq = sdramPins.filter(_.verilogPort.startsWith("sdram_DQ["))
        .sortBy(p => extractIndex(p.verilogPort))

      ctrl.foreach(p => sb.append(pinConstraint(p.fpgaPin, p.verilogPort)))
      ba.foreach(p => sb.append(pinConstraint(p.fpgaPin, p.verilogPort)))
      dqm.foreach(p => sb.append(pinConstraint(p.fpgaPin, p.verilogPort)))
      addr.foreach(p => sb.append(pinConstraint(p.fpgaPin, p.verilogPort)))
      dq.foreach(p => sb.append(pinConstraint(p.fpgaPin, p.verilogPort)))

      // Inlined rather than `source`d. These are two lines that depend only on
      // signal naming, and a source line would need a path relative to wherever
      // this file is written -- which the generator does not know. It was a
      // COMMENT before now, so a generated file adopted as-is would silently
      // have lost IOB packing. fpga/constraints/sdram_sdr.xdc stays until the
      // SDRAM exerciser flow is generated too; it still sources it.
      sb.append("\n# SDR SDRAM I/O block packing (deterministic timing)\n")
      sb.append("set_property IOB TRUE [get_ports {sdram_DQ[*]}]\n")
      sb.append("set_property IOB TRUE [get_ports {sdram_DQM[*]}]\n\n")
    }

    // Other peripheral pins (Ethernet, VGA, SD)
    if (otherDriverPins.nonEmpty) {
      sb.append("# Peripheral pins\n")
      otherDriverPins.foreach(p => sb.append(pinConstraint(p.fpgaPin, p.verilogPort)))
      sb.append("\n")
    }

    // Ethernet over RGMII (jop.io.Rgmii100). Its TX clock is the board PLL's
    // Ethernet output, which Vivado derives; RXC comes in from the PHY and is
    // asynchronous to everything (the MAC crosses it with CC FIFOs). A single
    // -group makes it asynchronous to every other clock without naming the
    // PLL's, which differ per board.
    val rgmii = config.devices.values.exists(d =>
      d.deviceType == DeviceType.Ethernet && d.params.getOrElse("rgmii", false) == true)
    if (rgmii) {
      sb.append("# Ethernet: RGMII at 100 Mb/s (jop.io.Rgmii100)\n")
      sb.append("# RXC is constrained at 8 ns, not 40: with no link, or before\n")
      sb.append("# autonegotiation settles, the PHY runs it at 125 MHz.\n")
      sb.append("create_clock -period 8.000 -name e_rxc [get_ports {e_rxc}]\n")
      sb.append("set_clock_groups -asynchronous -group [get_clocks e_rxc]\n")
      sb.append("# TXD/TX_CTL launch, and RXD/RX_CTL are captured, in IOB flops\n")
      sb.append("set_property IOB TRUE [get_ports {e_txd[*]}]\n")
      sb.append("set_property IOB TRUE [get_ports {e_txctl}]\n")
      sb.append("set_property IOB TRUE [get_ports {e_rxd[*]}]\n")
      sb.append("set_property IOB TRUE [get_ports {e_rxctl}]\n\n")
    }

    // Ethernet over GMII (RTL8211EG: the Wukong, the DB_FPGA boards). These are
    // the lines the hand-written rtl8211eg_gmii.xdc carried, which only the
    // Wukong's Makefile ever read: the DB_FPGA V5 flow reads this file alone,
    // so its GMII build had no e_rxc clock -- the defect that left the
    // EP4CGX150's receive domain untimed (status item 68). The PHY's
    // source-synchronous timing is not modelled: the inputs are captured in
    // IOB flops and false-pathed, the outputs leave with the PLL's GTX clock.
    val gmii = config.devices.values.find(d =>
      d.deviceType == DeviceType.Ethernet && d.params.getOrElse("gmii", false) == true)
    gmii.foreach { eth =>
      sb.append("# Ethernet: GMII at 1 Gb/s (RTL8211EG)\n")
      sb.append("create_clock -period 8.000 -name e_rxc [get_ports {e_rxc}]\n")
      sb.append("set_clock_groups -asynchronous -group [get_clocks e_rxc]\n")
      // The MAC transmits on the clock wizard's clk_125 output, which Vivado
      // names clk_125_<IP> -- clk_125_clk_wiz_0 on the DB_FPGA V5,
      // clk_125_ddr3_clk on the Wukong -- and reaches it through CC FIFOs, so it
      // is asynchronous to everything too. Ungrouped, the V5 timed those
      // crossings as synchronous and missed by 2.591 ns (xc7a100tDbEth).
      sb.append("set_clock_groups -asynchronous -group [get_clocks clk_125_*]\n")
      // A board that routes RX_CLK to a pin that is not clock-capable (the
      // DB_FPGA: J3:37 is L5 on the XC7A100T core) gets no dedicated IBUF->BUFG
      // path, and Vivado stops at Place 30-574 unless the design says a general
      // route is acceptable. Declared per preset, never assumed: on a board
      // whose RXC IS clock-capable this line would hide a real misplacement.
      if (eth.params.getOrElse("rxClkNotClockCapable", false) == true)
        sb.append("set_property CLOCK_DEDICATED_ROUTE FALSE [get_nets e_rxc_IBUF]\n")
      sb.append("set_false_path -from [get_ports {e_rxd[*] e_rxdv e_rxer}]\n")
      sb.append("set_false_path -to [get_ports {e_gtxc e_txd[*] e_txen e_txer}]\n")
      sb.append("set_property IOB TRUE [get_ports {e_rxd[*]}]\n")
      sb.append("set_property IOB TRUE [get_ports {e_rxdv}]\n")
      sb.append("set_property IOB TRUE [get_ports {e_rxer}]\n\n")
    }

    // Ports the design has but the board does not wire -- see Board.parkedPins.
    // Gated exactly as LpfGenerator gates them: an sdram_* port exists only
    // when the system uses SDR, and constraining a port that is not there is a
    // warning Vivado prints and nobody reads.
    val parked = assembly.boards.flatMap(_.parkedPins).filterNot {
      case (port, _) => port.startsWith("sdram_") && !usesSdr
    }
    if (parked.nonEmpty) {
      sb.append("# Ports the design has but this board does not wire -- see\n")
      sb.append("# Board.parkedPins for why these get a ball at all.\n")
      // A parked pin may be a connector reference ("SODIMM:57"): which pins are
      // free is a fact about the BASE board, which ball that is, the module's.
      parked.sortBy(_._1).foreach { case (port, ref) =>
        val ball = assembly.resolvePin(ref).getOrElse(
          sys.error(s"parked pin $port -> $ref does not resolve on ${assembly.name}"))
        sb.append(pinConstraint(ball, port))
      }
      sb.append("\n")
    }

    // Internal pulls for inputs the board leaves floating -- Board.portPulls.
    // Only for ports this file places: a pull on a port the design lacks is
    // the same unread Vivado warning as any other stray constraint.
    val placed = "PACKAGE_PIN \\S+ \\[get_ports \\{([^}]+)\\}\\]".r
      .findAllMatchIn(sb.toString).map(_.group(1)).toSet
    val pulls = assembly.boards.flatMap(_.portPulls).filter { case (port, _) => placed(port) }
    if (pulls.nonEmpty) {
      sb.append("# Internal pulls -- see Board.portPulls\n")
      pulls.sortBy(_._1).foreach { case (port, pull) =>
        sb.append(s"set_property PULLTYPE $pull [get_ports {$port}]\n")
      }
      sb.append("\n")
    }

    // Configuration properties
    sb.append("# Configuration\n")
    sb.append("set_property CFGBVS VCCO [current_design]\n")
    sb.append("set_property CONFIG_VOLTAGE 3.3 [current_design]\n")
    sb.append("set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]\n")
    // Vivado pulls unused pins DOWN by default. Where another chip drives FPGA
    // balls this design does not use, that pull fights it -- see
    // Board.unusedPinsFloat.
    if (assembly.boards.exists(_.unusedPinsFloat))
      sb.append("set_property BITSTREAM.CONFIG.UNUSEDPIN PULLNONE [current_design]\n")

    sb.toString
  }

  /** Format PACKAGE_PIN + IOSTANDARD for a single pin */
  private def pinConstraint(fpgaPin: String, port: String,
                            ioStandard: String = "LVCMOS33"): String =
    s"set_property PACKAGE_PIN $fpgaPin [get_ports {$port}]\n" +
    s"set_property IOSTANDARD $ioStandard [get_ports {$port}]\n"

  /** Extract numeric index from a bus port name like "sdram_ADDR[5]" */
  private def extractIndex(port: String): Int =
    port.dropWhile(_ != '[').drop(1).takeWhile(_ != ']').toIntOption.getOrElse(0)
}

/** Print, or write, the generated XDC for a Xilinx preset.
  *
  * `--write <path>` follows ConstGeneratorMain, which has emitted Const.java
  * into the Java build for as long as anyone has been running it -- the same
  * shape: config in, generated artefact out, consumed downstream, staleness
  * handled by make.
  *
  * Writing under spinalhdl/generated/ deliberately, alongside the Verilog: that
  * directory is already gitignored as build output, which is where generated
  * constraints belong if fpga/ is ever to stop being tracked by hand.
  */
object XdcGeneratorMain extends App {
  import jop.system.JopTopVerilog

  private val writeFlag = args.indexOf("--write")
  private val outPath =
    if (writeFlag >= 0 && args.length > writeFlag + 1) Some(args(writeFlag + 1)) else None
  // NB: guard on writeFlag >= 0. Without it, an absent --write gives
  // writeFlag = -1 and the test `i == writeFlag + 1` becomes `i == 0`, which
  // silently DELETES THE PRESET NAME and falls back to the default -- every
  // preset then renders as wukongSdram.
  private val presetArgs =
    if (writeFlag < 0) args
    else args.zipWithIndex.filterNot { case (_, i) => i == writeFlag || i == writeFlag + 1 }.map(_._1)

  val preset = presetArgs.headOption.getOrElse(
  sys.error(
    "no preset given. Pass the preset name as the first argument.\n" +
    "There is deliberately no default: this main writes a constraint or\n" +
    "project file, and a default silently produces a WELL-FORMED file for\n" +
    "the wrong board at the path --write names, which then builds."))
  val config = JopTopVerilog.resolvePreset(preset, presetArgs)
  val xdc = XdcGenerator.generate(config)

  outPath match {
    case Some(path) =>
      val f = new java.io.File(path)
      Option(f.getParentFile).foreach(_.mkdirs())
      val w = new java.io.PrintWriter(f)
      try w.print(xdc) finally w.close()
      println(s"Wrote $path")
    case None => println(xdc)
  }
}
